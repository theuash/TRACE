"""Turn a located statement table into metrics: label aliases, cell parsing, evidence."""

from __future__ import annotations

import re
from dataclasses import dataclass
from datetime import date
from decimal import Decimal
from typing import Any

from extraction import alias_memory
from extraction.locate import LocatedTable
from shared.schemas import (
    ExtractedMetric,
    Extractor,
    FilingRef,
    Metric,
    SourceEvidence,
    Unit,
)

SCALE_EXEMPT = {Metric.DILUTED_EPS}
DASHES = {"-", "\u2013", "\u2014"}
FOOTNOTE_RE = re.compile(r"^\(\d{1,2}[a-z]?\)$")
TRAILING_FOOTNOTE_RE = re.compile(r"\s*\(\d{1,2}[a-z]?\)$")

ALIASES: dict[Metric, tuple[str, ...]] = {
    Metric.REVENUE: (
        "total net sales",
        "total revenues",
        "total revenue",
        "net sales",
        "revenues",
        "revenue",
    ),
    Metric.NET_INCOME: ("net income", "net income (loss)", "net earnings"),
    Metric.OPERATING_INCOME: ("operating income", "income from operations", "operating profit"),
    Metric.GROSS_PROFIT: ("gross profit", "gross margin"),
    Metric.TOTAL_ASSETS: ("total assets",),
    Metric.TOTAL_LIABILITIES: ("total liabilities",),
    Metric.SHAREHOLDERS_EQUITY: (
        "total shareholders' equity",
        "total stockholders' equity",
        "total shareholders' equity (deficit)",
        "total equity",
    ),
    Metric.OPERATING_CASH_FLOW: (
        "net cash provided by operating activities",
        "net cash provided by (used in) operating activities",
        "cash generated by operating activities",
        "cash provided by operating activities",
        "net cash from operations",
        "cash from operations",
    ),
    Metric.CASH_AND_EQUIVALENTS: ("cash and cash equivalents",),
    Metric.DILUTED_EPS: ("diluted earnings per share", "diluted", "diluted net income per share"),
}

STATEMENT_FOR: dict[Metric, str] = {
    Metric.REVENUE: "income statement",
    Metric.NET_INCOME: "income statement",
    Metric.OPERATING_INCOME: "income statement",
    Metric.GROSS_PROFIT: "income statement",
    Metric.DILUTED_EPS: "income statement",
    Metric.TOTAL_ASSETS: "balance sheet",
    Metric.TOTAL_LIABILITIES: "balance sheet",
    Metric.SHAREHOLDERS_EQUITY: "balance sheet",
    Metric.CASH_AND_EQUIVALENTS: "balance sheet",
    Metric.OPERATING_CASH_FLOW: "cash flow",
}
WRONG_TABLE_PENALTY = 0.25


@dataclass
class Row:
    label: str
    raws: list[str]
    values: list[Decimal]
    wellformed: float


@dataclass
class Match:
    metric: Metric
    quality: float
    label_score: float
    statement: str
    row: Row
    table: LocatedTable


def normalise(text: str) -> str:
    out = text.replace("\u2019", "'").replace("\u2018", "'").replace("\u00a0", " ")
    out = out.replace("\u201c", '"').replace("\u201d", '"')
    out = " ".join(out.split()).strip().lower().strip(" .:$*")
    return TRAILING_FOOTNOTE_RE.sub("", out).strip(" .:$*")


def to_decimal(raw: str) -> tuple[Decimal | None, float]:
    """Printed cell -> (value in printed units, numeric_wellformed)."""
    text = raw.replace("$", "").replace(",", "").replace("\u00a0", "").strip()
    if text == "" or text in DASHES:
        return Decimal(0), 0.4
    score = 1.0
    negative = False
    if text.startswith("(") and text.endswith(")"):
        text, negative, score = text[1:-1], True, 0.6
    elif text.startswith("("):
        text, negative, score = text[1:], True, 0.6
    text = TRAILING_FOOTNOTE_RE.sub("", text).strip()
    if not re.fullmatch(r"-?\d+(\.\d+)?", text):
        return None, 0.0
    if text.startswith("-"):
        negative, text = True, text[1:]
    value = Decimal(text)
    return (-value if negative else value), score


def parse_rows(node: Any) -> list[Row]:
    rows: list[Row] = []
    for tr in node.xpath(".//tr"):
        cells = [" ".join(cell.text_content().split()) for cell in tr.xpath("./td|./th")]
        if len(cells) < 2 or not cells[0]:
            continue
        label, tail = cells[0], [cell for cell in cells[1:] if cell and cell != "$"]
        parsed = [(cell, *to_decimal(cell)) for cell in tail]
        parsed = [p for p in parsed if p[1] is not None]
        if len(parsed) > 2:
            kept = [p for p in parsed if not FOOTNOTE_RE.match(p[0])]
            parsed = kept or parsed
        if not parsed:
            continue
        rows.append(
            Row(
                label=label,
                raws=[p[0] for p in parsed],
                values=[p[1] for p in parsed],
                wellformed=min(p[2] for p in parsed),
            )
        )
    return rows


def match_label(label: str) -> tuple[Metric, float] | None:
    normalised = normalise(label)
    if not normalised:
        return None
    for metric, aliases in ALIASES.items():
        if normalised in aliases:
            return metric, 1.0
    learned = alias_memory.lookup(normalised)
    if learned is not None:
        return learned, alias_memory.LEARNED_LABEL_MATCH
    for metric, aliases in ALIASES.items():
        for alias in aliases:
            pattern = r"\b" + re.escape(alias).replace(r"\ ", r"[\s,]*") + r"\b"
            if re.fullmatch(pattern, normalised):
                return metric, 0.85
    for metric, aliases in ALIASES.items():
        for alias in aliases:
            for text in _qualified(normalised):
                if text.startswith(alias):
                    return metric, 0.7
    return None


QUALIFIERS = ("consolidated ", "combined ", "total company ")


def _qualified(normalised: str) -> list[str]:
    """The label itself plus the label with a leading 'Consolidated'/'Combined' stripped."""
    out = [normalised]
    out += [normalised[len(q) :] for q in QUALIFIERS if normalised.startswith(q)]
    return out


def pick_rows(located: dict[str, LocatedTable]) -> dict[Metric, Match]:
    """Best row per metric. Exact label hits beat suffix guesses and the wrong statement."""
    chosen: dict[Metric, Match] = {}
    for statement, table in located.items():
        for row in parse_rows(table.node):
            found = match_label(row.label)
            if found is None:
                continue
            metric, label_score = found
            if metric is Metric.DILUTED_EPS and abs(row.values[0]) >= 1000:
                continue  # a share count, not an earnings-per-share row
            penalty = 0.0 if STATEMENT_FOR.get(metric) == statement else WRONG_TABLE_PENALTY
            quality = label_score - penalty
            if metric not in chosen or quality > chosen[metric].quality:
                chosen[metric] = Match(metric, quality, label_score, statement, row, table)
    return chosen


def _period_end(table: LocatedTable, filing: FilingRef, index: int) -> date:
    if index < len(table.periods):
        return table.periods[index]
    if index == 0:
        return filing.period_end
    try:
        return filing.period_end.replace(year=filing.period_end.year - 1)
    except ValueError:
        return filing.period_end.replace(year=filing.period_end.year - 1, day=28)


def _signals(match: Match, filing: FilingRef) -> dict[str, float]:
    table = match.table
    period_clear = 0.4
    if table.periods:
        period_clear = 1.0 if table.periods[0] == filing.period_end else 0.8
    return {
        "label_match": match.label_score,
        "table_type": 1.0 if STATEMENT_FOR.get(match.metric) == match.statement else 0.6,
        "unit_clarity": 1.0 if table.scale_clear else 0.3,
        "period_clarity": period_clear,
        "numeric_wellformed": match.row.wellformed,
        "extractor_agreement": 0.5,
    }


def build_metric(match: Match, filing: FilingRef, column: int = 0) -> ExtractedMetric:
    raw = match.row.raws[column]
    printed, _ = to_decimal(raw)
    scale = 1 if match.metric in SCALE_EXEMPT else match.table.scale
    year = filing.fiscal_year if column == 0 else filing.fiscal_year - 1
    return ExtractedMetric(
        ticker=filing.company.ticker,
        metric=match.metric,
        fiscal_year=year,
        period_end=_period_end(match.table, filing, column),
        value=(printed or Decimal(0)) * scale,
        unit=Unit.USD_PER_SHARE if match.metric in SCALE_EXEMPT else Unit.USD,
        scale=scale,
        raw_text=raw,
        extractor=Extractor.TABLE,
        confidence=1.0,
        confidence_signals=_signals(match, filing),
        evidence=SourceEvidence(
            snippet=" | ".join([match.row.label, *match.row.raws]),
            matched_text=raw,
            location=f"{match.statement}, row '{match.row.label}'",
            table_index=match.table.table_index,
            row_label=match.row.label,
            source_url=filing.url,
        ),
    )


def build_metrics(
    filing: FilingRef, located: dict[str, LocatedTable]
) -> tuple[list[ExtractedMetric], list[ExtractedMetric]]:
    metrics: list[ExtractedMetric] = []
    prior: list[ExtractedMetric] = []
    for match in pick_rows(located).values():
        metrics.append(build_metric(match, filing, 0))
        if len(match.row.values) > 1:
            prior.append(build_metric(match, filing, 1))
    return metrics, prior
